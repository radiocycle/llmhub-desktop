package dev.radiocycle.llmhub.data.model

/** A ready-made provider template. Selecting one only pre-fills a [Provider]; nothing is locked. */
data class ProviderPreset(
    val id: String,
    val name: String,
    val apiMode: ApiMode,
    val baseUrl: String,
    val models: List<String>,
    val defaultModel: String,
    val headers: List<HeaderEntry> = emptyList(),
    val keyHint: String = "",
    val needsKey: Boolean = true,
    val openAiMode: OpenAiMode = OpenAiMode.WIRE,
    val reasoningEffort: ReasoningEffort = ReasoningEffort.DEFAULT,
    val effortParameter: String = "",
    val customEffort: String = "",
) {
    fun toProvider(priority: Int): Provider = Provider(
        name = name,
        apiMode = apiMode,
        openAiMode = openAiMode,
        reasoningEffort = reasoningEffort,
        effortParameter = effortParameter,
        customEffort = customEffort,
        baseUrl = baseUrl,
        models = models,
        defaultModel = defaultModel,
        headers = headers,
        priority = priority,
        presetId = id,
    )
}

